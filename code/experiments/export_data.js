'use strict';
// Exports the data behind the experiments into code/data/, so the artifact contains the processed inputs and
// not only the code that generates them. Needs no node and no experiment rerun (about 10 s):
//
//   EPOCHCRED_SEED=epochcred-2026 node experiments/export_data.js
//
// Writes
//   data/datasets/*.csv               synthetic student records used by each experiment (16 attributes each)
//   data/datasets/MANIFEST.json       every (experiment, n, seed) record set with the SHA-256 of its canonical
//                                     JSON; sets too large for CSV are listed here and regenerated by makeRecords
//   data/example_epoch/*.json         a worked two-epoch example: records, epoch values and k-of-n signatures,
//                                     published revocation sets, holder wallets, presentations, verifier output
//   data/SHA256SUMS                   checksums of every file in data/ and results/
// All records are synthetic (offchain/lib/data.js); no personal data exist anywhere in the artifact.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { ethers } = require('../offchain/lib/chain');
const C = require('../offchain/lib/credential');
const H = require('../offchain/lib/hash');
const { makeRecords } = require('../offchain/lib/data');
const { privKey } = require('../offchain/lib/rng');

const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'data');
const DS = path.join(DATA, 'datasets');
const EX = path.join(DATA, 'example_epoch');
for (const d of [DATA, DS, EX]) fs.mkdirSync(d, { recursive: true });

const sha256 = (buf) => crypto.createHash('sha256').update(buf).digest('hex');
// JSON with byte arrays as 0x-hex and BigInt as decimal strings
const toJSON = (x) => JSON.stringify(x, (k, v) => {
  if (typeof v === 'bigint') return v.toString();
  if (v instanceof Uint8Array) return H.bytesToHex(v);
  return v;
}, 2);
const csvCell = (v) => { const s = String(v); return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s; };
function writeCsv(file, recs) {
  const lines = [['row', ...C.SCHEMA_KEYS].join(',')];
  recs.forEach((r, i) => lines.push([i, ...C.SCHEMA_KEYS.map((k) => csvCell(r[k]))].join(',')));
  fs.writeFileSync(file, lines.join('\n') + '\n');
}

// ------------------------------------------------------------------ 1. record sets used by the experiments
// (experiment, n, seed) exactly as in the experiment scripts; CSV written when n <= CSV_MAX
const CSV_MAX = 4096;
const sets = [
  { experiment: 'dictionary_attack.js (RQ6, Table 10)', n: 200, seed: 31337 },
  { experiment: 'security_tests.js (Table 4, main fixture)', n: 16, seed: 7 },
  { experiment: 'security_tests.js (fraud-proof fixture)', n: 4, seed: 9 },
  { experiment: 'security_tests.js (restoration fixture)', n: 4, seed: 10 },
  { experiment: 'security_tests.js (late-relay fixture, T48)', n: 2, seed: 12 },
  { experiment: 'gas_experiments.js (RQ1-RQ3, Tables 5-6)', n: 4096, seed: 1 },
  { experiment: 'breakdown.js (verification breakdown)', n: 1024, seed: 3 },
  { experiment: 'verify_experiments.js (baseline documents, Table 9)', n: 1024, seed: 77 },
  { experiment: 'gen_vectors.js (cross-implementation vectors)', n: 1, seed: 99 },
  { experiment: 'deploy_testnet.js (Sepolia, 10 epochs x 256)', n: 2560, seed: 5 },
];
// verification sweeps: makeRecords(B, B + r) for every configuration of Table 8
for (const B of [16, 64, 256, 1024, 4096, 16384, 65536]) sets.push({ experiment: `verify_experiments.js (Table 8, B=${B}, r=1024)`, n: B, seed: B + 1024 });
for (const r of [0, 16, 64, 256, 1024, 4096, 16384, 32768]) sets.push({ experiment: `verify_experiments.js (Table 8, B=1024, r=${r})`, n: 1024, seed: 1024 + r });

const manifest = { generator: 'offchain/lib/data.js makeRecords(n, seed)', schema: C.SCHEMA_KEYS, note: 'Synthetic records. Regenerate any set with makeRecords(n, seed); the SHA-256 is over JSON.stringify(records).', sets: [] };
const seen = new Set();
for (const s of sets) {
  const recs = makeRecords(s.n, s.seed);
  const entry = { ...s, sha256_json: sha256(JSON.stringify(recs)) };
  const name = `records_n${s.n}_seed${s.seed}.csv`;
  if (s.n <= CSV_MAX) {
    if (!seen.has(name)) writeCsv(path.join(DS, name), recs);
    seen.add(name);
    entry.csv = `datasets/${name}`;
  }
  manifest.sets.push(entry);
}
fs.writeFileSync(path.join(DS, 'MANIFEST.json'), JSON.stringify(manifest, null, 2));

// ------------------------------------------------------------------ 2. worked example: two epochs, k = 3 of 5
const officers = Array.from({ length: 5 }, (_, i) => new ethers.Wallet(privKey(`example-officer-${i}`)));
const holders = Array.from({ length: 8 }, (_, i) => new ethers.Wallet(privKey(`example-holder-${i}`)));
const issuerId = ethers.id('example-institute');
const REGISTRY = '0x000000000000000000000000000000000000dEaD'; // placeholder: example is not deployed
const issuer = new C.Issuer({ issuerId, officers, threshold: 3, chainId: 31337, registry: REGISTRY });
const recs = makeRecords(8, 2026);
const T0 = 1767225600; // same fixed genesis time as the local node
const validUntil = T0 + 10 * 365 * 86400;

const e1 = issuer.buildEpoch(recs.slice(0, 6).map((attrs, i) => ({ attrs, holder: holders[i].address, validUntil })));
const rec1 = { issuanceRoot: e1.value.issuanceRoot, revocationRoot: e1.value.revocationRoot, timestamp: T0 + 12, count: e1.value.count, prevHead: e1.value.prevHead };
issuer.confirm(e1.value, rec1.timestamp);
const revokedSet1 = [];
// epoch 2: two new credentials, and credentials 1 and 4 of epoch 1 are revoked
issuer.revoke(e1.wallets[1].nullifier);
issuer.revoke(e1.wallets[4].nullifier);
const e2 = issuer.buildEpoch(recs.slice(6, 8).map((attrs, i) => ({ attrs, holder: holders[6 + i].address, validUntil })));
const rec2 = { issuanceRoot: e2.value.issuanceRoot, revocationRoot: e2.value.revocationRoot, timestamp: T0 + 24, count: e2.value.count, prevHead: e2.value.prevHead };
issuer.confirm(e2.value, rec2.timestamp);
const revokedSet2 = [e1.wallets[1].nullifier, e1.wallets[4].nullifier].map(H.bytesToHex).sort();

const chain = { issRec: rec1, issDigest: C.recordDigest(rec1), latestRec: rec2, head: C.recordDigest(rec2), now: T0 + 60, frozen: false };
const challenge = 'nonce:example-verifier-0001';
const keys = ['studentName', 'degree', 'major', 'graduationYear'];
const results = e1.wallets.map((w, i) => {
  const p = C.present(w, holders[i], keys, issuer.revoked, challenge);
  return { credential: i, revoked: [1, 4].includes(i), disclosed: keys, presentation_bytes: C.presentationSize(p), verifier: C.verify(p, chain, challenge), presentation: p };
});

fs.writeFileSync(path.join(EX, 'records.json'), toJSON(recs));
fs.writeFileSync(path.join(EX, 'epochs.json'), toJSON({
  issuerId, threshold: 3, officers: officers.map((o) => o.address), registry: REGISTRY, chainId: 31337,
  epochs: [
    { epoch: 1, signed_value: e1.value, signatures_k3: e1.sigs, record: rec1, digest: C.recordDigest(rec1), published_revocation_set: revokedSet1 },
    { epoch: 2, signed_value: e2.value, signatures_k3: e2.sigs, record: rec2, digest: C.recordDigest(rec2), published_revocation_set: revokedSet2 },
  ],
}));
fs.writeFileSync(path.join(EX, 'holder_wallets.json'), toJSON([...e1.wallets, ...e2.wallets]));
fs.writeFileSync(path.join(EX, 'presentations_and_verification.json'), toJSON({ challenge, chain_view: chain, results }));
const okCount = results.filter((r) => r.verifier.ok).length;
if (okCount !== 4 || results.some((r) => r.revoked === r.verifier.ok)) throw new Error('example epoch: unexpected verification outcome');

// ------------------------------------------------------------------ 3. checksums of data/ and results/
const files = [];
const walk = (dir) => { for (const f of fs.readdirSync(dir).sort()) { const p = path.join(dir, f); if (fs.statSync(p).isDirectory()) walk(p); else if (!p.endsWith('SHA256SUMS') && !p.endsWith('anvil.log')) files.push(p); } };
walk(DATA); walk(path.join(ROOT, 'results'));
fs.writeFileSync(path.join(DATA, 'SHA256SUMS'), files.map((f) => `${sha256(fs.readFileSync(f))}  ${path.relative(ROOT, f)}`).join('\n') + '\n');

console.log(`datasets: ${manifest.sets.length} record sets (${seen.size} CSV files) -> data/datasets/`);
console.log(`example epoch: 8 credentials, 2 revoked; verifier accepted ${okCount}/6 of epoch 1 (revoked ones rejected) -> data/example_epoch/`);
console.log(`checksums: ${files.length} files -> data/SHA256SUMS`);
